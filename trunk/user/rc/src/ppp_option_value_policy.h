#ifndef PADAVAN_PPP_OPTION_VALUE_POLICY_H
#define PADAVAN_PPP_OPTION_VALUE_POLICY_H

#include <errno.h>
#include <stddef.h>
#include <string.h>

/*
 * Escape values written into pppd's single-quoted option syntax.
 * Reject control characters so one configured value cannot turn into multiple
 * option lines. Custom option text has a separate mode that preserves LF/TAB.
 * Both modes fail on overflow instead of returning raw or truncated input.
 */
static int
ppp_option_escape_internal(const char *value, char *out, size_t out_size,
                           int allow_line_breaks)
{
	const unsigned char *src;
	size_t needed, extra, used;

	if (!out || out_size == 0) {
		errno = EINVAL;
		return -1;
	}
	out[0] = '\0';
	if (!value) {
		errno = EINVAL;
		return -1;
	}

	needed = 1; /* terminating NUL */
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src < 0x20 &&
		    !(allow_line_breaks && (*src == '\n' || *src == '\t'))) {
			errno = EINVAL;
			return -1;
		}
		if (*src == 0x7f) {
			errno = EINVAL;
			return -1;
		}

		extra = (*src == '\'' || *src == '\\') ? 2U : 1U;
		if (needed > (size_t)-1 - extra) {
			errno = EOVERFLOW;
			return -1;
		}
		needed += extra;
	}

	if (needed > out_size) {
		errno = EOVERFLOW;
		return -1;
	}

	used = 0;
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src == '\'' || *src == '\\')
			out[used++] = '\\';
		out[used++] = (char)*src;
	}
	out[used] = '\0';

	return 0;
}

static int
ppp_option_value_escape(const char *value, char *out, size_t out_size)
{
	return ppp_option_escape_internal(value, out, out_size, 0);
}

/* WAN callback identity is generated by RC and cannot be overridden by the
 * user-provided free-form PPP options. Ignore comments while inspecting keys. */
static int
ppp_option_text_reject_ipparam(const char *value)
{
	const unsigned char *p, *start;
	size_t key_len;

	if (!value) {
		errno = EINVAL;
		return -1;
	}
	p = (const unsigned char *)value;
	while (*p) {
		while (*p == ' ' || *p == '\t')
			++p;
		if (*p == '#') {
			while (*p && *p != '\n')
				++p;
			if (*p == '\n')
				++p;
			continue;
		}
		if (*p == '\n') {
			++p;
			continue;
		}
		start = p;
		while (*p && *p != '\n' && *p != ' ' && *p != '\t' && *p != '=')
			++p;
		key_len = (size_t)(p - start);
		if (key_len == 7 && memcmp(start, "ipparam", 7) == 0) {
			errno = EPERM;
			return -1;
		}
		while (*p && *p != '\n')
			++p;
		if (*p == '\n')
			++p;
	}
	return 0;
}

static int
ppp_option_text_escape(const char *value, char *out, size_t out_size)
{
	if (ppp_option_text_reject_ipparam(value) != 0) {
		if (out && out_size > 0)
			out[0] = '\0';
		return -1;
	}
	return ppp_option_escape_internal(value, out, out_size, 1);
}


/*
 * Copy one unquoted scalar into line-oriented L2TP config syntax.
 * These values are not shell strings: reject all control bytes, CR/LF and
 * overlong values instead of allowing one configured value to create options
 * or sections on subsequent lines.
 */
static int
ppp_config_line_value_copy(const char *value, char *out, size_t out_size)
{
	const unsigned char *src;
	size_t used;

	if (!out || out_size == 0) {
		errno = EINVAL;
		return -1;
	}
	out[0] = '\0';
	if (!value) {
		errno = EINVAL;
		return -1;
	}

	used = 0;
	for (src = (const unsigned char *)value; *src; ++src) {
		if (*src < 0x20 || *src == 0x7f) {
			out[0] = '\0';
			errno = EINVAL;
			return -1;
		}
		if (used >= out_size - 1) {
			out[0] = '\0';
			errno = EOVERFLOW;
			return -1;
		}
		out[used++] = (char)*src;
	}
	out[used] = '\0';
	return 0;
}

#endif /* PADAVAN_PPP_OPTION_VALUE_POLICY_H */
